_SOURCE: Final[str] = '''\
"""__QUALIFIED__: a Godwit source plugin. DATA PLANE: it reads customer rows.

Generated by `godwit-sdk new source`. The backend is an in-memory stand-in: replace
`Backend` with your client, keeping the five methods' contracts --

* `snapshot`, `columns`, `partitions` read metadata only, never rows;
* `read` returns ONLY the columns it is asked for;
* nothing prints, logs directly, or puts a value in an exception message.
"""

from __future__ import annotations

import datetime as _dt
from collections.abc import Iterable, Mapping, Sequence
from typing import Final, Self

import pyarrow as pa
from godwit_sdk import (
    LogicalType,
    Partition,
    Snapshot,
    SourceBase,
    TableName,
    logical_type,
    source,
)

__all__ = ["Backend", "__CLASS__"]

_EPOCH: Final[_dt.datetime] = _dt.datetime(2024, 1, 1, tzinfo=_dt.UTC)


class Backend:
    """Stand-in for the real client: tables by name, all in memory."""

    def __init__(self, tables: Mapping[str, pa.Table]) -> None:
        self.tables = dict(tables)


@source(
    name="__NAME__",
    namespace="__NAMESPACE__",
    version="0.1.0",
    summary="__SUMMARY__",
)
class __CLASS__(SourceBase):
    """Reads tables from a `Backend`."""

    def __init__(self, backend: Backend) -> None:
        self._backend = backend

    def snapshot(self, table: TableName, *, at: _dt.datetime | None) -> Snapshot:
        del table, at
        return Snapshot(snapshot_id="v1", sequence_number=1, committed_at=_EPOCH)

    def columns(self, table: TableName, snapshot: Snapshot) -> Mapping[str, LogicalType]:
        del snapshot
        schema = self._backend.tables[table.name].schema
        return {field.name: logical_type(field.type) for field in schema}

    def partitions(self, table: TableName, snapshot: Snapshot) -> Sequence[Partition]:
        del snapshot
        data = self._backend.tables[table.name]
        return [Partition(key="all", estimated_bytes=data.nbytes, row_count=data.num_rows)]

    def read(
        self, table: TableName, partition: Partition, columns: Sequence[str]
    ) -> Iterable[pa.RecordBatch | pa.Table]:
        del partition
        self.log.debug("read.started", columns=len(columns))
        yield self._backend.tables[table.name].select(list(columns))

    @classmethod
    def for_conformance(cls, tables: Mapping[str, pa.Table]) -> Self:
        return cls(Backend(tables))
'''

_SKETCH: Final[str] = '''\
"""__QUALIFIED__: a Godwit sketch plugin. DATA PLANE: it summarises row values.

Generated by `godwit-sdk new sketch`: an exact counter of non-null items. Replace the
state, `merge`, `encode` and `_decode_body` with your algorithm; the decorator checks
the monoid laws when the module is imported, and the conformance kit checks them again
under hypothesis. If the state ever holds anything taken from a row -- or lets someone
test whether a value was present -- set VALUE_BEARING = True and SENSITIVITY = DATA_VALUE.
"""

from __future__ import annotations

import struct
from collections.abc import Mapping, Sequence
from typing import ClassVar, Final, Self

from godwit_sdk import (
    Acquisition,
    ErrorBound,
    ItemFlavour,
    MergeExactness,
    Sensitivity,
    SketchBase,
    SketchKind,
    sketch,
)

__all__ = ["__CLASS__"]

_BODY: Final[struct.Struct] = struct.Struct(">Q")


@sketch(
    name="__NAME__",
    namespace="__NAMESPACE__",
    version="0.1.0",
    summary="__SUMMARY__",
)
class __CLASS__(SketchBase):
    """Counts non-null items. Exact, so merge is exactly associative and commutative."""

    KIND: ClassVar[SketchKind] = SketchKind.EXACT_COUNT
    CODEC: ClassVar[str] = "__NAMESPACE__-__NAME__-v1"
    SCHEMA_VERSION: ClassVar[int] = 1
    VALUE_BEARING: ClassVar[bool] = False
    SENSITIVITY: ClassVar[Sensitivity | None] = Sensitivity.DERIVED_STATISTIC
    MERGE_EXACTNESS: ClassVar[MergeExactness] = MergeExactness.EXACT
    ITEM_FLAVOUR: ClassVar[ItemFlavour] = ItemFlavour.CATEGORICAL
    ACQUISITION: ClassVar[Acquisition] = Acquisition.COMPUTED_STATISTIC
    DEFAULT_PARAMS: ClassVar[Mapping[str, int | float | str | bool]] = {}

    def __init__(self, count: int = 0) -> None:
        self._count = count

    @classmethod
    def identity(cls, params: Mapping[str, int | float | str | bool]) -> Self:
        del params
        return cls()

    @classmethod
    def from_items(
        cls, items: Sequence[object], params: Mapping[str, int | float | str | bool]
    ) -> Self:
        del params
        return cls(sum(1 for item in items if item is not None))

    @property
    def params(self) -> Mapping[str, int | float | str | bool]:
        return {}

    @property
    def population(self) -> int:
        return self._count

    def merge(self, other: Self) -> Self:
        return type(self)(self._count + other._count)

    def error_bound(self) -> ErrorBound:
        return ErrorBound(kind="exact", note="an exact count")

    def estimate(self) -> float:
        return float(self._count)

    def encode(self) -> bytes:
        return self.CODEC.encode("ascii") + _BODY.pack(self._count)

    @classmethod
    def _decode_body(cls, payload: bytes) -> Self:
        (count,) = _BODY.unpack(payload[len(cls.CODEC) :])
        return cls(count)
'''

_DETECTOR: Final[str] = '''\
"""__QUALIFIED__: a Godwit detector plugin. Control plane: it never sees a row.

Generated by `godwit-sdk new detector`: flags a jump in a sketch's row count against the
mean of its reference windows, with a Poisson z-test. Replace `examine` with your test.
Bump the version in the decorator whenever output could change for identical input.
"""

from __future__ import annotations

import math
from collections.abc import Sequence
from typing import ClassVar

from godwit_sdk import (
    BaseSketch,
    DetectorBase,
    Direction,
    EvidenceKind,
    HypothesisTest,
    detector,
)

__all__ = ["__CLASS__"]


@detector(
    name="__NAME__",
    namespace="__NAMESPACE__",
    version="0.1.0",
    summary="__SUMMARY__",
)
class __CLASS__(DetectorBase):
    """One test per sketch: did the row count move beyond Poisson noise?"""

    EVIDENCE: ClassVar[EvidenceKind] = EvidenceKind.RATE_CHANGE
    CODECS: ClassVar[frozenset[str]] = frozenset({"godwit-kll-v1"})
    TESTS_PER_SKETCH: ClassVar[int] = 1

    def examine(
        self, current: BaseSketch, reference: Sequence[BaseSketch]
    ) -> Sequence[HypothesisTest]:
        expected = sum(sketch.population for sketch in reference) / len(reference)
        z = (current.population - expected) / math.sqrt(max(expected, 1.0))
        return (
            HypothesisTest(
                method="poisson_row_count",
                statistic=z,
                effect=current.population / max(expected, 1.0) - 1.0,
                p_value=math.erfc(abs(z) / math.sqrt(2.0)),
                direction=Direction.UP if z > 0 else Direction.DOWN,
                baseline=expected,
                statistic_unit="z",
                effect_unit="relative_change",
            ),
        )
'''

