_CONTEXT: Final[str] = '''\
"""__QUALIFIED__: a Godwit context-source plugin (explained-away events, L3).

Generated by `godwit-sdk new context`. The backend is an in-memory list of records:
replace it with your calendar, deploy tracker or incident system. Return plain fields;
the SDK taints labels and column names and builds the events.
"""

from __future__ import annotations

import datetime as _dt
from collections.abc import Iterable, Sequence
from typing import Self

from godwit_sdk import ContextBase, ContextRecord, context

__all__ = ["__CLASS__"]


@context(
    name="__NAME__",
    namespace="__NAMESPACE__",
    version="0.1.0",
    summary="__SUMMARY__",
)
class __CLASS__(ContextBase):
    """Lists records from an in-memory backend."""

    def __init__(self, records: Sequence[ContextRecord]) -> None:
        self._records = tuple(records)

    def fetch(self, *, start: _dt.datetime, end: _dt.datetime) -> Iterable[ContextRecord]:
        del start, end  # over-returning is fine: the SDK filters to the window
        return self._records

    @classmethod
    def for_conformance(cls, records: Sequence[ContextRecord]) -> Self:
        return cls(records)
'''

